/**
 * Подписка.
 *
 * Пока заглушка: экрана оплаты нет, продуктов в App Store Connect тоже.
 * Но граница платного уже нужна коду, поэтому она объявлена здесь одна
 * на всё приложение — когда появится RevenueCat, менять придётся только
 * этот файл.
 *
 * Что за деньги, а что бесплатно (решено 2026-08-07):
 *
 * — Бесплатно: таймер целиком. Кольцо-регулятор, наборы длительностей,
 *   живая активность на экране блокировки, темы, языки. Этого хватает,
 *   чтобы приложением пользоваться каждый день.
 *
 * — Платно: всё, что связано с Deep Focus. Сама блокировка, строгий
 *   режим, расписание, несколько списков приложений.
 *
 * Границу пришлось переносить. Сначала платным было «несколько списков»,
 * но количество здесь не дефицит: один список, куда сложено всё, закрывает
 * потребность целиком, и платить оказывалось не за что. То же с
 * длительностями — регулятор бесплатный, значит и свои длительности
 * бесплатны по существу.
 *
 * Дефицитна не блокировка сама по себе, а невозможность передумать:
 * человек борется не с телефоном, а с собой, и через двадцать минут
 * сам себе разрешит. Поэтому строгий режим и расписание — не довесок
 * к платному, а его сердцевина.
 *
 * ВАЖНО про строгий режим: это трение, а не замок. Приложение всегда
 * можно удалить и поставить заново. Так у всех на iOS — сильнее держать
 * система не позволяет. Трения хватает, чтобы порыв прошёл.
 */

/**
 * Ради проверки платных веток поменять здесь на `true`.
 *
 * Пока экрана оплаты нет, стоит `true`: иначе Deep Focus нельзя было бы
 * проверить на устройстве вообще. Вернуть в `false`, когда появится
 * RevenueCat и настоящий триал.
 */
const SUBSCRIBED = true;

export function useSubscribed(): boolean {
  return SUBSCRIBED;
}
